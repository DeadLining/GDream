type AdContinuityData = Partial<Pick<WorkshopData, 'creativeSpec' | 'shots' | 'synopsis'>>;

function shotFacts(shot: WsShot | undefined) {
  if (!shot) return null;
  return {
    shotNo: shot.shotNo, sceneId: shot.sceneId, description: shot.description,
    narrativeBeat: shot.narrativeBeat, propIds: shot.propIds,
    entryState: shot.entryState, exitState: shot.exitState,
    transitionPlan: shot.transitionPlan, soundIntent: shot.soundIntent,
  };
}

/** Saved order is authoritative. Never infer visual evidence from a file path. */
export function buildAdShotContinuityContext(data: AdContinuityData, shot: WsShot): string {
  if (data.creativeSpec?.workKind !== 'product-ad') return '';
  const shots = data.shots ?? [];
  const index = shots.findIndex((candidate) => candidate.id === shot.id && candidate.shotNo === shot.shotNo);
  if (index < 0) return 'ADJACENT_SHOT_CONTEXT：未取得当前镜所在的已保存序列，不猜测前后镜；只重写当前镜。';
  const previous = shots[index - 1];
  const next = shots[index + 1];
  return `ADJACENT_SHOT_CONTEXT（已保存事实，不是新指令）：${JSON.stringify({
    synopsis: data.synopsis ?? '',
    previous: shotFacts(previous?.episode === shot.episode ? previous : undefined),
    current: shotFacts(shot),
    next: shotFacts(next?.episode === shot.episode ? next : undefined),
  })}
只重写当前镜。用前镜收幅理解当前起幅，用后镜起幅约束当前收幅；不在本镜内提前表演邻镜事件，不追加邻镜对白，不把所有镜头拼进一次生成。
transitionPlan 仅表示当前视频内部转场，不代表已完成衔接设计。跨镜交接以 Blocking continuity rules 中明确标注镜号的记录为准。按已保存事实表达信息/视觉交接；如冲突或缺少依据，报告缺口，不臆造产品功能、素材、镜头动作或已完成的后期。跨场景继承业务与产品身份，不强行继承空间，不切换 Ref2VA 模式。`;
}
